import { EventBlueprint } from './types';
import { formatNumber } from './format';

/**
 * Compiles a comprehensive, markdown-formatted operational run-sheet.
 * Formats all master sections: Executive Catering, Budget Matrix, Timeline,
 * Vendor War-Room, and Tailored Creative Concepts.
 *
 * @param blueprint - The master event blueprint
 * @returns Fully formatted, production-ready markdown run-sheet
 *
 * @example
 * const runSheet = generateRunSheetMarkdown(blueprint);
 */
export function generateRunSheetMarkdown(blueprint: EventBlueprint): string {
  const { eventSummary, budgetBreakdown, timeline, vendorChecklist, personalizedIdeas } = blueprint;
  const sym = eventSummary.currency === 'INR' ? '₹' : '$';

  return `# ${eventSummary.title} — Operational Run-Sheet & Master Blueprint
**Category:** ${eventSummary.category} | **City:** ${eventSummary.city} | **Guest Count (PAX):** ${eventSummary.guestCount}
**Total Budget:** ${eventSummary.currency} ${formatNumber(eventSummary.totalBudget)} | **Tagline:** "${eventSummary.tagline}"

---

## 1. Executive Catering & Waste-Matrix
- **Recommended Plates:** ${eventSummary.cateringMatrix.recommendedPlates} (Buffer: ${eventSummary.cateringMatrix.bufferPercentage}%)
- **Estimated Per-Plate Cost:** ${sym}${formatNumber(eventSummary.cateringMatrix.perPlateCostEstimate)}
- **Waste Prevention Strategy:** ${eventSummary.cateringMatrix.wastePreventionTip}

---

## 2. Zero-Sum Budget Allocation Matrix
| Category | Allocated Amount | Percentage | Priority | Lock Status | AI Saving Hack |
| :--- | :--- | :--- | :--- | :--- | :--- |
${budgetBreakdown
  .map(
    c =>
      `| **${c.category}** | ${sym}${formatNumber(c.allocatedAmount)} | ${c.percentage}% | ${c.priority} | ${c.locked ? '🔒 Locked' : '🔓 Dynamic'} | ${c.aiSavingHack} |`
  )
  .join('\n')}

---

## 3. Run-of-Show Critical Path Timeline
| Phase | Time Slot | Milestone Title | Owner | Criticality | Status | Dependency / Risk |
| :--- | :--- | :--- | :--- | :--- | :--- | :--- |
${timeline
  .map(
    t =>
      `| ${t.phase} | ${t.timeSlot} | **${t.title}** | ${t.owner} | ${t.criticality} | ${t.status.toUpperCase()} | ${t.dependencyNote} |`
  )
  .join('\n')}

---

## 4. Vendor War-Room & Negotiation Status
| Vendor Service | Est. Market Rate | Negotiated Cost | Booking Target | Status | Anti-Fraud Red Flag |
| :--- | :--- | :--- | :--- | :--- | :--- |
${vendorChecklist
  .map(
    v =>
      `| **${v.vendorType}** | ${sym}${formatNumber(v.estimatedCost)} | ${sym}${formatNumber(v.negotiatedCost !== undefined ? v.negotiatedCost : v.estimatedCost)} | ${v.bookingDeadline} | ${v.status.toUpperCase()} | ${v.redFlagWarning} |`
  )
  .join('\n')}

---

## 5. Tailored Creative Concepts & Viral Blueprints
${personalizedIdeas
  .map(
    (idea, i) => `### 5.${i + 1} ${idea.title} [${idea.category}]
- **Impact Rating:** ${idea.impactScore} | **Estimated Investment:** ${idea.estimatedCost === 0 ? 'FREE / Zero-Cost' : `${sym}${formatNumber(idea.estimatedCost)}`}
- **Shortlisted:** ${idea.shortlisted ? 'Yes (Active in Plan)' : 'No'}
- **Step-by-Step SOP:** ${idea.executionBlueprint}
`
  )
  .join('\n')}

---
*Generated by VibeOps Autonomous Event Production War-Room (Powered by Groq LPU & Llama 3.3)*
`;
}

/**
 * Serializes the complete event blueprint into formatted JSON string.
 *
 * @param blueprint - The active event blueprint
 * @returns 2-space indented JSON string representation
 *
 * @example
 * const json = serializeBlueprintJSON(blueprint);
 */
export function serializeBlueprintJSON(blueprint: EventBlueprint): string {
  return JSON.stringify(blueprint, null, 2);
}

/**
 * Triggers a browser file download using dynamic blob URL allocation.
 * Safe for all desktop and mobile browsers.
 *
 * @param content - Text content or serialized data
 * @param filename - Target download file name
 * @param mimeType - MIME type string (e.g. 'application/json', 'text/markdown')
 *
 * @example
 * triggerFileDownload(md, 'event_runsheet.md', 'text/markdown;charset=utf-8;');
 */
export function triggerFileDownload(content: string, filename: string, mimeType: string): void {
  if (typeof window === 'undefined') return;

  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = filename;
  document.body.appendChild(anchor);
  anchor.click();
  document.body.removeChild(anchor);
  URL.revokeObjectURL(url);
}

/**
 * Executes a full export workflow for a given format (PDF/print, JSON, or Markdown).
 *
 * @param blueprint - Event blueprint to export
 * @param format - Export format target
 */
export function exportBlueprint(blueprint: EventBlueprint, format: 'pdf' | 'json' | 'markdown'): void {
  if (typeof window === 'undefined') return;

  if (format === 'pdf') {
    window.print();
    return;
  }

  const baseTitle = blueprint.eventSummary.title.replace(/\s+/g, '_');

  if (format === 'json') {
    const content = serializeBlueprintJSON(blueprint);
    triggerFileDownload(content, `${baseTitle}_blueprint.json`, 'application/json');
    return;
  }

  if (format === 'markdown') {
    const content = generateRunSheetMarkdown(blueprint);
    triggerFileDownload(content, `${baseTitle}_operational_runsheet.md`, 'text/markdown;charset=utf-8;');
  }
}

