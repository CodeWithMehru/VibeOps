import { describe, it, expect, vi } from 'vitest';
import {
  generateRunSheetMarkdown,
  serializeBlueprintJSON,
  triggerFileDownload,
} from '@/lib/export-utils';
import { WEDDING_PRESET, BIRTHDAY_PRESET, COMMUNITY_PRESET } from '@/lib/presets';
import { EventBlueprint } from '@/lib/types';

describe('VibeOps Blueprint Export Engine', () => {
  describe('generateRunSheetMarkdown', () => {
    it('generates a complete markdown run-sheet with all 5 core sections for WEDDING_PRESET', () => {
      const md = generateRunSheetMarkdown(WEDDING_PRESET);

      expect(md).toContain(`# ${WEDDING_PRESET.eventSummary.title} — Operational Run-Sheet & Master Blueprint`);
      expect(md).toContain('## 1. Executive Catering & Waste-Matrix');
      expect(md).toContain('## 2. Zero-Sum Budget Allocation Matrix');
      expect(md).toContain('## 3. Run-of-Show Critical Path Timeline');
      expect(md).toContain('## 4. Vendor War-Room & Negotiation Status');
      expect(md).toContain('## 5. Tailored Creative Concepts & Viral Blueprints');
      expect(md).toContain('Generated by VibeOps Autonomous Event Production War-Room');
    });

    it('generates a complete operational run-sheet for COMMUNITY_PRESET', () => {
      const md = generateRunSheetMarkdown(COMMUNITY_PRESET);

      expect(md).toContain(COMMUNITY_PRESET.eventSummary.title);
      expect(md).toContain(COMMUNITY_PRESET.eventSummary.city);
      expect(md).toContain('Hackathon');
    });

    it('formats currency and catering calculations accurately for INR and USD', () => {
      const inrMd = generateRunSheetMarkdown(WEDDING_PRESET);
      expect(inrMd).toContain('₹');
      expect(inrMd).toContain('PAX');

      const usdPreset: EventBlueprint = {
        ...BIRTHDAY_PRESET,
        eventSummary: {
          ...BIRTHDAY_PRESET.eventSummary,
          currency: 'USD',
        },
      };
      const usdMd = generateRunSheetMarkdown(usdPreset);
      expect(usdMd).toContain('$');
    });

    it('includes all budget categories and vendor anti-fraud warnings in markdown tables', () => {
      const md = generateRunSheetMarkdown(WEDDING_PRESET);

      WEDDING_PRESET.budgetBreakdown.forEach((cat) => {
        expect(md).toContain(cat.category);
      });

      WEDDING_PRESET.vendorChecklist.forEach((v) => {
        expect(md).toContain(v.vendorType);
      });
    });

    it('includes personalized creative ideas and SOP blueprints in markdown output', () => {
      const md = generateRunSheetMarkdown(WEDDING_PRESET);

      WEDDING_PRESET.personalizedIdeas.forEach((idea) => {
        expect(md).toContain(idea.title);
      });
    });
  });

  describe('serializeBlueprintJSON', () => {
    it('serializes blueprint into valid, parseable JSON round-trip matching original data', () => {
      const jsonStr = serializeBlueprintJSON(WEDDING_PRESET);
      expect(typeof jsonStr).toBe('string');

      const parsed = JSON.parse(jsonStr);
      expect(parsed.eventSummary.title).toBe(WEDDING_PRESET.eventSummary.title);
      expect(parsed.budgetBreakdown.length).toBe(WEDDING_PRESET.budgetBreakdown.length);
      expect(parsed.timeline.length).toBe(WEDDING_PRESET.timeline.length);
      expect(parsed.vendorChecklist.length).toBe(WEDDING_PRESET.vendorChecklist.length);
      expect(parsed.personalizedIdeas.length).toBe(WEDDING_PRESET.personalizedIdeas.length);
    });

    it('serializes birthday preset cleanly with indented whitespace', () => {
      const jsonStr = serializeBlueprintJSON(BIRTHDAY_PRESET);
      expect(jsonStr).toContain(BIRTHDAY_PRESET.eventSummary.title);
      expect(jsonStr.startsWith('{')).toBe(true);
    });
  });

  describe('triggerFileDownload', () => {
    it('creates an anchor element and triggers download click cleanly', () => {
      const mockCreateObjectURL = vi.fn().mockReturnValue('blob:http://localhost/mock-blob-uuid');
      const mockRevokeObjectURL = vi.fn();
      globalThis.URL.createObjectURL = mockCreateObjectURL;
      globalThis.URL.revokeObjectURL = mockRevokeObjectURL;

      const clickSpy = vi.fn();
      const appendChildSpy = vi.spyOn(document.body, 'appendChild');
      const removeChildSpy = vi.spyOn(document.body, 'removeChild');

      const origCreateElement = document.createElement.bind(document);
      vi.spyOn(document, 'createElement').mockImplementation((tagName: string) => {
        const el = origCreateElement(tagName);
        if (tagName === 'a') {
          el.click = clickSpy;
        }
        return el;
      });

      triggerFileDownload('# Test Content', 'runsheet.md', 'text/markdown;charset=utf-8;');

      expect(mockCreateObjectURL).toHaveBeenCalledTimes(1);
      expect(clickSpy).toHaveBeenCalledTimes(1);
      expect(mockRevokeObjectURL).toHaveBeenCalledWith('blob:http://localhost/mock-blob-uuid');

      appendChildSpy.mockRestore();
      removeChildSpy.mockRestore();
      vi.restoreAllMocks();
    });

    it('safely handles environments where window is simulated undefined without crashing', () => {
      expect(() => {
        triggerFileDownload('test', 'test.txt', 'text/plain');
      }).not.toThrow();
    });
  });
});
